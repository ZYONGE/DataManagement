/* ============================================================
   [8] 변경 확정 : COMMIT
   ------------------------------------------------------------
   문법 : COMMIT;   /   ROLLBACK;   /   SAVEPOINT 이름;
   - COMMIT   : 지금까지의 INSERT/UPDATE/DELETE 를 영구 확정한다.
                확정 후에는 ROLLBACK 으로 되돌릴 수 없다.
   - ROLLBACK : 마지막 COMMIT 이후의 변경을 전부 취소한다.
   - SQL Developer 는 기본이 수동 커밋이라 COMMIT 을 직접 해야 한다.
     (sqlplus 도 동일. 커밋 전에는 다른 세션에서 변경이 보이지 않는다.)
   - DDL(CREATE/DROP 등)을 실행하면 그 시점에 자동으로 커밋되므로,
     커밋하지 않은 DML이 함께 확정되어 버리는 점에 주의.
   ============================================================ */
COMMIT;
