/* ████████████████████████████████████████████████████████████
   DML — 데이터 조작어 (Data Manipulation Language)
   ------------------------------------------------------------
   테이블 "안의 행(row)"을 넣고, 바꾸고, 지우는 명령.
   INSERT / UPDATE / DELETE / MERGE 가 여기에 속한다.

   DDL과 달리 DML은 자동 커밋되지 않는다.
   → COMMIT 해야 확정되고, ROLLBACK 하면 되돌릴 수 있다.
   → 커밋 전에는 "나에게만" 보이고 다른 세션에는 보이지 않는다.
     (SQL Developer에서 넣은 데이터가 sqlplus에서 안 보이는 이유)

   선행 조건 : [7]번 PLAYER_PRACTICE 실습은 DDL.sql 에서
               테이블을 먼저 만들어야 동작한다.
   ████████████████████████████████████████████████████████████ */


/* ████ INSERT — 행 추가 ████████████████████████████████████ */

/* ============================================================
   [1] 컬럼을 지정해서 넣기 (권장 방식)
   ------------------------------------------------------------
   문법 : INSERT INTO 테이블명 (컬럼1, 컬럼2, ...) VALUES (값1, 값2, ...);
   - 적지 않은 컬럼에는 NULL(또는 DEFAULT 값)이 들어간다.
   - 컬럼 목록과 VALUES 의 값은 "개수와 순서"가 정확히 맞아야 한다.
   - 문자/날짜 값은 작은따옴표로 감싸고, 숫자는 그냥 쓴다.
   - 테이블 구조가 바뀌어도 깨지지 않으므로 실무에서는 이 방식을 쓴다.
   ============================================================ */
insert into player (player_id, player_name, team_id, birth_date)
values ('29990', '손흥민', 'K07', '2000-01-01');


/* ============================================================
   [2] 컬럼 목록을 생략하고 넣기
   ------------------------------------------------------------
   문법 : INSERT INTO 테이블명 VALUES (값1, 값2, ... 모든컬럼);
   - 컬럼 목록을 생략하면 "테이블에 정의된 순서대로 전부" 적어야 한다.
   - 값이 없는 자리는 NULL 이라고 직접 써 준다. 하나라도 빠지면 오류.
   - PLAYER 테이블은 컬럼이 13개라 NULL을 10개 채운 것이다.
   - 컬럼 순서를 외워야 하고 테이블이 바뀌면 바로 깨지므로 권장하지 않는다.
     (DESC player; 로 순서를 먼저 확인하면 편하다 → DDL.sql [1])
   ============================================================ */
insert into player
values ('29991', '이승우', 'K07', NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL);


/* ============================================================
   [3] 한 번에 여러 행 넣기 : INSERT ALL
   ------------------------------------------------------------
   문법 : INSERT ALL
            INTO 테이블명 (컬럼...) VALUES (값...)
            INTO 테이블명 (컬럼...) VALUES (값...)
          SELECT * FROM dual;
   - Oracle 전용 문법. INTO 절을 늘리면 행을 계속 추가할 수 있다.
   - 마지막의 SELECT 는 형식상 반드시 필요하다. 넣을 값이 고정값뿐이면
     행이 딱 1개인 더미 테이블 dual 을 써서 "한 바퀴만 돌게" 만든다.
   - dual : Oracle이 기본 제공하는 1행 1컬럼짜리 가상 테이블.
   - INTO 절마다 서로 다른 테이블을 지정할 수도 있다.
   ============================================================ */
-- 넣기 전 상태 확인
select * from stadium;

INSERT ALL
    INTO stadium (stadium_id, stadium_name)
    VALUES ('TP1', '임시경기장 1')
    INTO stadium (stadium_id, stadium_name)
    VALUES ('TP2', '임시경기장 2')
SELECT * FROM dual;

-- 넣은 결과 확인
select *
from stadium
where stadium_id like 'TP1';

select *
from stadium
where stadium_id like 'TP2';


/* ████ UPDATE — 행 수정 ████████████████████████████████████ */

/* ============================================================
   [4] 기존 행의 값 바꾸기
   ------------------------------------------------------------
   문법 : UPDATE 테이블명 SET 컬럼1 = 값1, 컬럼2 = 값2 WHERE 조건;
   - SET 절에 바꿀 컬럼을 쉼표로 나열한다.
   - ★ WHERE 를 빠뜨리면 "테이블의 모든 행"이 바뀐다. 가장 흔한 사고.
     실행 전에 같은 WHERE 로 SELECT 해서 대상 행을 먼저 확인하는 습관.
   - SET 에는 계산식도 쓸 수 있다. 예) SET WEIGHT = WEIGHT + 3
   ============================================================ */
update stadium
set stadium_name = '우리경기장'
where stadium_id = 'TP2';


/* ████ DELETE — 행 삭제 ████████████████████████████████████ */

/* ============================================================
   [5] 조건에 맞는 행 지우기
   ------------------------------------------------------------
   문법 : DELETE FROM 테이블명 WHERE 조건;
   - 행을 지울 뿐 테이블 구조는 그대로 남는다. (구조까지 지우면 DROP)
   - ★ WHERE 를 빠뜨리면 전체 행이 삭제된다. UPDATE와 같은 주의.
   - DELETE 는 DML이라 ROLLBACK 으로 되돌릴 수 있지만,
     TRUNCATE 는 DDL이라 되돌릴 수 없다. (대신 훨씬 빠르다)
   ============================================================ */
delete from stadium
where stadium_id = 'TP1';


