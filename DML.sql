/* ============================================================
   [6-3] 경기 결과 수정 : 조건이 두 개인 UPDATE
   ------------------------------------------------------------
   포인트
   - SCHEDULE 의 기본키는 (STADIUM_ID, SCHE_DATE) 두 컬럼을 묶은
     복합 기본키라서, 한 경기를 특정하려면 두 조건을 AND로 묶어야 한다.
   - SCHE_DATE 가 '20250601' 처럼 따옴표 안에 들어가는 것은
     이 컬럼이 DATE 가 아니라 문자형이기 때문이다.
   - 참고 : 해당 경기 행이 아직 없으면 "0개 행 갱신"으로 끝난다.
     오류가 아니라 조건에 맞는 행이 없다는 뜻이다.
   ============================================================ */
UPDATE SCHEDULE
SET HOME_SCORE = 5,
    AWAY_SCORE = 3
WHERE STADIUM_ID = 'S05'
  AND SCHE_DATE = '20250601';


