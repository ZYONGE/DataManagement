/* ============================================================
   [7-2] 조건에 맞는 행 수정하기
   ------------------------------------------------------------
   포인트
   - ① SET WEIGHT = WEIGHT + 3
       오른쪽의 WEIGHT 는 "수정 전 값"이다. 자기 자신을 읽어
       계산한 결과를 다시 넣는 방식.
   - ② SET 절에 컬럼 두 개를 쉼표로 나열해 한 번에 바꾼다.
       WHERE 에 조건 두 개를 AND 로 묶어 대상을 좁힌다.
   ============================================================ */
-- ① FW 선수 몸무게 +3kg
UPDATE PLAYER_PRACTICE
SET WEIGHT = WEIGHT + 3
WHERE POSITION = 'FW';

-- ② MF 이고 키 180cm 미만 → 포지션 FW, 등번호 11
UPDATE PLAYER_PRACTICE
SET POSITION = 'FW',
    BACK_NO  = 11
WHERE POSITION = 'MF'
  AND HEIGHT < 180;

-- ③ 수정된 선수 확인 (①: P9991, ②: P9992)
SELECT PLAYER_NAME, POSITION, BACK_NO, HEIGHT, WEIGHT
FROM PLAYER_PRACTICE
WHERE PLAYER_ID IN ('P9991', 'P9992')
ORDER BY WEIGHT DESC;


/* ============================================================
   [7-3] 조건에 맞는 행 삭제하기
   ------------------------------------------------------------
   포인트
   - ① 앞의 [7-2]① 에서 FW 몸무게가 +3 된 상태이므로,
       여기서 어떤 행이 지워지는지는 "앞 문장의 실행 결과"에 달려 있다.
       → DML은 실행 순서가 결과를 바꾼다.
   - ② LIKE '박%' : 이름이 '박'으로 시작하는 행. 와일드카드 % 는
       "0글자 이상 아무 문자" 를 뜻한다. (DQL.sql [8] 참고)
   ============================================================ */
-- ① FW 이고 몸무게 75kg 미만 선수 삭제
DELETE FROM PLAYER_PRACTICE
WHERE POSITION = 'FW'
  AND WEIGHT < 75;

-- ② 이름이 '박'으로 시작하고 키 180cm 이상 선수 삭제
DELETE FROM PLAYER_PRACTICE
WHERE PLAYER_NAME LIKE '박%'
  AND HEIGHT >= 180;

-- ③ 남은 선수 확인
SELECT PLAYER_NAME, POSITION, HEIGHT, WEIGHT
FROM PLAYER_PRACTICE
ORDER BY PLAYER_NAME ASC;


