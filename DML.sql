/* ============================================================
   [7-1] 연습 데이터 3건 넣기
   ------------------------------------------------------------
   포인트
   - 같은 형태의 INSERT 를 반복할 때는 컬럼 목록을 고정해 두면
     값만 바꿔 가며 복사해 쓸 수 있어 실수가 줄어든다.
   - 넣은 직후 SELECT 로 확인하는 것이 DML의 기본 습관이다.
   ============================================================ */
INSERT INTO PLAYER_PRACTICE (PLAYER_ID, PLAYER_NAME, TEAM_ID, POSITION, BACK_NO, HEIGHT, WEIGHT)
VALUES ('P9991', '김민수', 'K01', 'FW', 9, 185, 80);

INSERT INTO PLAYER_PRACTICE (PLAYER_ID, PLAYER_NAME, TEAM_ID, POSITION, BACK_NO, HEIGHT, WEIGHT)
