/* ============================================================
   [6-2] 팀 추가 : 외래키(FK)가 걸린 테이블에 넣기
   ------------------------------------------------------------
   포인트
   - TEAM.STADIUM_ID 는 STADIUM 테이블을 참조하는 외래키다.
     그래서 'S05' 경기장을 먼저 만든 뒤에([6-1]) 팀을 넣어야 한다.
     순서를 바꾸면 ORA-02291 (무결성 제약조건 위배)이 난다.
   - ORIG_YYYY 에 '2025' 처럼 따옴표를 쓴 것은 이 컬럼이
