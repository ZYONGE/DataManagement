/* ============================================================
   [0] 테이블 구조 확인 : DESCRIBE / DESC
   ------------------------------------------------------------
   문법 : DESCRIBE 테이블명;   (축약형 DESC 테이블명;)
   - 테이블의 컬럼명, NULL 허용 여부(NOT NULL), 데이터 타입을 보여준다.
   - 데이터를 조회하는 것이 아니라 "구조(스키마)"를 확인하는 명령이다.
   - SQL 표준 문장이 아니라 Oracle(SQL*Plus / SQL Developer) 등
     도구에서 제공하는 명령이라서 DBMS마다 지원 여부가 다르다.
   - 테이블명은 대소문자를 구분하지 않는다. (TEAM = team)
   ============================================================ */
describe TEAM;      -- 정식 표기
desc TEAM;          -- 축약 표기 (결과는 위와 동일)
desc stadium;       -- 경기장 테이블 구조
desc schedule;      -- 경기 일정 테이블 구조
desc player;        -- 선수 테이블 구조


/* ============================================================
   [기본 1] 전체 조회 : SELECT *
   ------------------------------------------------------------
   문법 : SELECT 속성명 FROM 테이블명(객체명);
   - * (애스터리스크)는 "모든 컬럼"을 의미한다.
   - 컬럼 순서는 테이블을 만들 때 정의한 순서대로 출력된다.
   - 실습용으로는 편하지만, 실무에서는 필요한 컬럼만 적는 것이 좋다.
   ============================================================ */
select * from player;
/* select 속성명 from 테이블명(객체명) */


/* ============================================================
   [기본 2] 특정 컬럼 조회 + 별칭(ALIAS) : AS
   ------------------------------------------------------------
   문법 : SELECT 컬럼명 [AS] 별칭 FROM 테이블명;
   - 조회할 컬럼을 쉼표(,)로 구분해 원하는 것만 나열한다.
   - AS 별칭 : 결과 화면에 표시되는 컬럼 제목만 바꾼다.
     (실제 테이블의 컬럼명은 바뀌지 않음)
   - AS는 생략 가능 → e_player_name 영문이름 도 같은 의미.
   - 별칭에 공백·특수문자가 있거나 대소문자를 그대로 살리려면
     큰따옴표로 감싼다. 예) e_player_name AS "English Name"
   ============================================================ */
select player_name, e_player_name as 영문이름 from player;


/* ============================================================
   [기본 3] 정렬 : ORDER BY
   ------------------------------------------------------------
   문법 : SELECT ... FROM ... ORDER BY 컬럼명 [ASC | DESC];
   - ASC  : 오름차순 (작은 값 → 큰 값), 기본값이라 생략 가능
   - DESC : 내림차순 (큰 값 → 작은 값)
   - ORDER BY는 항상 SELECT 문의 "맨 마지막"에 위치한다.
   - Oracle에서 NULL은 가장 큰 값으로 취급되어
     ASC일 때 맨 뒤, DESC일 때 맨 앞에 나온다.
   ============================================================ */
select back_no from player
order by back_no asc;


/* ============================================================
   [실습 1] 등번호 순으로 선수 목록 보기
   ------------------------------------------------------------
   기능 : 선수 ID, 이름, 등번호, 포지션을 등번호 오름차순으로 출력
   포인트
   - SELECT 절에 여러 컬럼을 쉼표로 나열
   - ORDER BY back_no ASC → 등번호가 작은 선수부터 출력
   - 정렬 기준 컬럼(back_no)은 SELECT 목록에 없어도 사용할 수 있다.
   ============================================================ */
/*1*/
select player_id, player_name, back_no, position from player
order by back_no asc;


/* ============================================================
   [실습 2] 선수 ID 역순으로 보기
   ------------------------------------------------------------
   기능 : 선수 ID와 이름을 선수 ID 내림차순으로 출력
   포인트
   - ORDER BY player_id DESC → 큰 값부터 출력
   - player_id가 문자형(VARCHAR2 등)이면 숫자 크기가 아니라
     "문자열 사전순"으로 비교된다.
     예) '9' 가 '10' 보다 크게 취급됨 (첫 글자 '9' > '1')
   ============================================================ */
/*2*/
select player_id, player_name from player
order by player_id desc;


/* ============================================================
   [실습 3] 조건 검색 + 정렬 : WHERE + ORDER BY
   ------------------------------------------------------------
   기능 : 포지션이 미드필더('MF')인 선수만 골라 키 오름차순으로 출력
   문법 : SELECT ... FROM ... WHERE 조건 ORDER BY ...;
   포인트
   - WHERE 절 : 조건이 참(TRUE)인 행(row)만 결과에 남긴다.
   - 문자 값은 작은따옴표(' ')로 감싼다. → 'MF'
   - 컬럼명(POSITION / position)은 대소문자를 구분하지 않지만,
     따옴표 안의 "데이터 값"은 대소문자를 구분한다. ('mf' ≠ 'MF')
   - 절(clause)의 작성 순서 : SELECT → FROM → WHERE → ORDER BY
     실제 실행 순서       : FROM → WHERE → SELECT → ORDER BY
   ============================================================ */
/*3*/
select player_id, POSITION, height from player
where position = 'MF'
order by height asc;


/* ============================================================
   [추가] 특정 팀 소속 선수 조회 : WHERE
   ------------------------------------------------------------
   기능 : 팀 ID가 'K06'인 팀의 선수 ID, 이름, 팀 ID 출력
   포인트
   - WHERE 컬럼 = '값' 형태의 가장 기본적인 조건 검색
   - 문장 끝의 세미콜론(;)은 SQL 문의 끝을 알리는 구분자이다.
     여러 문장을 한 파일에서 실행할 때는 반드시 붙이는 것이 좋다.
   ============================================================ */
select player_id, player_name, team_id from player
where team_id = 'K06';
