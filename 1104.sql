-- 1. HEIGHT 180 이상, POSITION FW
SELECT PLAYER_NAME, POSITION, HEIGHT
FROM PLAYER
WHERE HEIGHT >= 180
  AND POSITION = 'FW';

-- 2. 키 170~185, 포지션 FW 또는 MF
SELECT PLAYER_NAME, POSITION, HEIGHT
FROM PLAYER
WHERE HEIGHT BETWEEN 170 AND 185
  AND POSITION IN ('FW', 'MF');

-- 3. 이름에 '김' 포함, 키가 NULL 아님
SELECT PLAYER_NAME, HEIGHT
FROM PLAYER
WHERE PLAYER_NAME LIKE '%김%'
  AND HEIGHT IS NOT NULL;

-- 4. 포지션 FW/MF, 키 175 이상, 몸무게 70~85 (키 · 몸무게 NULL 제외)
SELECT PLAYER_NAME, POSITION, HEIGHT, WEIGHT
FROM PLAYER
WHERE POSITION IN ('FW', 'MF')
  AND HEIGHT >= 175
  AND WEIGHT BETWEEN 70 AND 85
  AND HEIGHT IS NOT NULL
  AND WEIGHT IS NOT NULL;

-- 5. 이름이 '김'으로 시작하지 않고 포지션 DF/GK
SELECT PLAYER_NAME, POSITION, TEAM_ID
FROM PLAYER
WHERE PLAYER_NAME NOT LIKE '김%'
  AND POSITION IN ('DF', 'GK');

-- 6. PRODUCT 테이블 생성
CREATE TABLE PRODUCT (
    PRODUCT_ID   NUMBER(5)    CONSTRAINT PRODUCT_PK PRIMARY KEY,
    PRODUCT_NAME VARCHAR2(50) NOT NULL,
    PRICE        NUMBER(10)   CONSTRAINT PRODUCT_PRICE_CK CHECK (PRICE > 0),
    CATEGORY     VARCHAR2(30),
    STOCK        NUMBER(5)
);

-- 7. INSERT ALL 로 3건 삽입 후 확인
INSERT ALL
    INTO PRODUCT VALUES (101, 'Laptop', 1500000, 'Electronics', 10)
    INTO PRODUCT VALUES (102, 'Mouse',    30000, 'Electronics', 50)
    INTO PRODUCT VALUES (103, 'Desk',    200000, 'Furniture',   20)
SELECT * FROM DUAL;
COMMIT;

SELECT * FROM PRODUCT;

-- 8. Electronics 상품 가격 10% 인상 후 조회
UPDATE PRODUCT
SET PRICE = PRICE * 1.1
WHERE CATEGORY = 'Electronics';
COMMIT;

SELECT * FROM PRODUCT;

-- 9. 가격 50000 미만 또는 재고 0 인 상품 삭제 후 조회
DELETE FROM PRODUCT
WHERE PRICE < 50000
   OR STOCK = 0;
COMMIT;

SELECT * FROM PRODUCT;

